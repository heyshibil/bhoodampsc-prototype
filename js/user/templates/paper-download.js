/* Flow template: Paper Download. Card -> Category -> Year -> papers -> download (or upgrade if premium). */
(function () {
  const BP = (window.BP = window.BP || {});
  const { html, raw, icon, iconTile } = BP.ui;
  const byOrder = (a, b) => a.order - b.order;
  const kb = (bytes) => Math.round((bytes || 0) / 1024) + ' KB';

  BP.templates = BP.templates || {};
  BP.templates.paper_download = {
    render(card, section, ctx) {
      const st = BP.store.state;
      const base = '#/user/card/' + card.id;
      const cats = st.downloadCategories.slice().sort(byOrder);
      const cat = cats.find((c) => c.id === ctx.query.cat);

      if (!cat) {
        return html`${BP.u.pageHead({ back: '#/user/home', backLabel: 'Home', crumbs: [section.title], title: card.title, sub: 'Choose a category' })}
          ${cats.length ? html`<div class="list">${cats.map((c) => {
            const papers = BP.store.q.papersFor(card.id, c.id);
            const years = BP.store.q.yearsWithPapers(card.id, c.id);
            return html`<a class="list-row" href="${base}?cat=${c.id}">${iconTile('folder')}
              <span class="lr-main"><span class="lr-title">${c.title}</span><span class="lr-meta">${papers.length ? papers.length + (papers.length === 1 ? ' paper' : ' papers') + ' · ' + (years.length > 1 ? years[years.length - 1] + ' to ' + years[0] : years[0]) : 'No papers yet'}</span></span>
              ${raw(BP.icon('chevron-right', 'chev'))}</a>`;
          })}</div>` : BP.ui.emptyState({ icon: 'folder', title: 'No categories yet', text: 'Categories appear here once the admin adds them.' })}`;
      }

      const years = BP.store.q.yearsWithPapers(card.id, cat.id);
      const wanted = Number(ctx.query.year);
      const year = years.includes(wanted) ? wanted : years[0];
      const papers = year ? BP.store.q.papersFor(card.id, cat.id, year) : [];
      return html`${BP.u.pageHead({ back: base, backLabel: card.title, crumbs: [section.title, card.title], title: cat.title + ' papers' })}
        ${years.length ? html`<div class="filters"><div class="filter-group">
          <span class="filter-label" id="pyear-label">Year</span>
          <div class="chip-row" role="group" aria-labelledby="pyear-label">${years.map((y) => html`<button type="button" class="chip" aria-pressed="${String(y === year)}" data-act="year" data-value="${y}">${y}</button>`)}</div>
        </div></div>` : ''}
        ${papers.length ? html`<div class="list">${papers.map((p) => {
          const locked = BP.u.isLocked(p, ctx.user);
          return html`<div class="list-row">
            ${iconTile(locked ? 'lock' : 'file-text', p.isPremium ? 'accent' : '')}
            <span class="lr-main"><span class="lr-title">${p.title}</span><span class="lr-meta">PDF · ${kb(p.fileSize)} · ${p.year}</span><span class="row-wrap gap-2 lr-tags">${BP.u.accessTag(p, ctx.user)}</span></span>
            <span class="lr-end">
              ${locked ? html`<button type="button" class="btn btn--secondary btn--sm" data-act="unlock" aria-label="Unlock ${p.title}">${icon('crown')}<span class="hide-xs">Unlock</span></button>`
                : html`<button type="button" class="btn btn--primary btn--sm" data-act="download" data-id="${p.id}" aria-label="Download ${p.title}">${icon('download')}<span class="hide-xs">Download</span></button>`}
            </span>
          </div>`;
        })}</div>` : BP.ui.emptyState({ icon: 'file-text', title: 'No papers here yet', text: 'Papers appear here once they are approved.' })}`;
    },
    actions: {
      year(el, e, ctx) { BP.router.go(ctx.path, { cat: ctx.query.cat, year: el.dataset.value }, { replace: true }); },
      unlock() { BP.premium.upgrade({ reason: 'This paper is for Premium members.' }); },
      download(el) {
        const p = BP.store.byId('papers', el.dataset.id);
        el.disabled = true;
        const label = el.innerHTML;
        el.innerHTML = '<span class="spinner"></span>';
        setTimeout(() => {
          saveFile(samplePdf(p), p.fileName);
          el.disabled = false; el.innerHTML = label;
          BP.ui.toast('Downloaded ' + p.fileName, { type: 'success' });
        }, 700);
      },
    },
  };

  /* A tiny one-page PDF so the download is a real file. ASCII only. */
  function samplePdf(p) {
    const cat = BP.store.byId('downloadCategories', p.categoryId);
    const clean = (s) => String(s).replace(/[^\x20-\x7E]/g, '-').replace(/([()\\])/g, '\\$1');
    const lines = [['F2', 20, 'BoodhamPSC'], ['F1', 16, p.title], ['F1', 12, 'Category: ' + (cat ? cat.title : '') + '   Year: ' + p.year],
      ['F1', 12, ''], ['F1', 12, 'This is a sample file generated by the clickable prototype.'], ['F1', 12, 'In the real app, the uploaded question paper (PDF) downloads here.']];
    let y = 780;
    const stream = 'BT ' + lines.map(([f, size, text]) => { const s = '/' + f + ' ' + size + ' Tf 1 0 0 1 56 ' + y + ' Tm (' + clean(text) + ') Tj'; y -= size + 14; return s; }).join(' ') + ' ET';
    const objs = [
      '<< /Type /Catalog /Pages 2 0 R >>',
      '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
      '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 4 0 R /F2 5 0 R >> >> /Contents 6 0 R >>',
      '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
      '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>',
      '<< /Length ' + stream.length + ' >>\nstream\n' + stream + '\nendstream',
    ];
    let out = '%PDF-1.4\n';
    const offsets = objs.map((o, i) => { const at = out.length; out += (i + 1) + ' 0 obj\n' + o + '\nendobj\n'; return at; });
    const xref = out.length;
    out += 'xref\n0 ' + (objs.length + 1) + '\n0000000000 65535 f \n' + offsets.map((o) => String(o).padStart(10, '0') + ' 00000 n \n').join('');
    out += 'trailer\n<< /Size ' + (objs.length + 1) + ' /Root 1 0 R >>\nstartxref\n' + xref + '\n%%EOF';
    return new Blob([out], { type: 'application/pdf' });
  }
  function saveFile(blob, name) {
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    a.download = name;
    document.body.appendChild(a);
    a.click();
    setTimeout(() => { URL.revokeObjectURL(a.href); a.remove(); }, 1000);
  }
})();
